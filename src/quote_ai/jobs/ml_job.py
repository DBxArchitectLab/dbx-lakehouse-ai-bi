"""Job entry point for win prediction (Season 3): one command per task of the quote_ai_ml_* jobs.

AI-12  quote_ai_ml_features (nightly)
  setup         the history, feature, label, training set and model tables (src/quote_ai/ml/*_tables.sql) and the
                on-demand function price_vs_customer_current_pct
  seed          DBxLab's synthetic quote history, customer prices and inventory history (quote_ai.mock.generate_dbxlab),
                only into empty tables: the injected drift of AI-14 survives a rerun. --force rewrites them
  features      quote_labels and the three feature tables, point in time (quote_ai.ml.features), merged with
                Feature Engineering
  training-set  win_training_set: Feature Engineering's point-in-time training set with its time split; fails on a
                leak, and when it disagrees with the pure builder
AI-13  quote_ai_train
  train         rule, logreg and gbt tracked in MLflow; the selection rule; the decision into model_selection
AI-14  quote_ai_ml_register, quote_ai_ml_score (nightly)
  register      the selected run -> win_model @challenger; @champion only if it beats the champion on the latest month;
                the endpoint follows @champion; EXECUTE for the app (and, from AI-18, the agent)
  score         every open quote scored by @champion into open_quote_scores (append), with the run's assertions
  monitor       create or update the inference monitor on open_quote_scores, and refresh it
  drift         AI-14's demo: append a month of falling customer prices (rerun features and score after)

Common: --catalog and --schemas logical=physical,... (from ${resources.schemas.<key>.name}). Needs Spark, MLflow and
databricks-feature-engineering (Databricks); the logic is plain Python, tested in tests/quote_ai/test_features.py,
test_train.py and test_score.py. Everything here is demo data: an educational simulation with a planted signal.
"""
import argparse
import inspect
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

SRC = Path(inspect.currentframe().f_code.co_filename).resolve().parents[2]
sys.path.insert(0, str(SRC))
from quote_ai.mock import generate_dbxlab  # noqa: E402
from quote_ai.ml import features as F  # noqa: E402
from quote_ai.ml import monitor, register, score, train  # noqa: E402
from quote_ai.ml import metrics  # noqa: E402
from quote_ai.storage import sql_files  # noqa: E402

ML = SRC / "quote_ai" / "ml"
COMMANDS = ["setup", "seed", "features", "training-set", "train", "register", "score", "monitor", "drift"]


def parse(argv):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("command", choices=COMMANDS)
    p.add_argument("--catalog", required=True)
    p.add_argument("--schemas", default="")
    p.add_argument("--experiment", default=train.EXPERIMENT, help="train: the MLflow experiment")
    p.add_argument("--git-commit", default="unknown", help="train: ${bundle.git.commit}")
    p.add_argument("--endpoint", default=None, help="register: the serving endpoint that follows @champion")
    p.add_argument("--app-sp", default=None, help="register: the app's service principal (EXECUTE on the model)")
    p.add_argument("--force", action="store_true", help="seed: rewrite non-empty history tables")
    return p.parse_args(argv)


def _rows(spark, sql: str) -> list[dict]:
    return [r.asDict() for r in spark.sql(sql).collect()]


def _df(spark, rows: list[dict], fqn: str):
    """Rows as a DataFrame with the table's own schema and column order (no inference on null columns)."""
    schema = spark.table(fqn).schema
    return spark.createDataFrame([tuple(r.get(f.name) for f in schema.fields) for r in rows], schema=schema)


def _empty(spark, fqn: str) -> bool:
    return spark.table(fqn).limit(1).count() == 0


# ------------------------------------------------------------------ AI-12

def setup(spark, names: dict) -> None:
    # AI-03 created quote_history with fewer columns; AI-12's history replaces it (demo data, regenerated by seed)
    cols = {c.name for c in spark.catalog.listColumns(f"{names['sales']}.quote_history")} \
        if spark.catalog.tableExists(f"{names['sales']}.quote_history") else None
    if cols is not None and "sent_at" not in cols:
        spark.sql(f"DROP TABLE {names['sales']}.quote_history")
    for f in ("feature_tables.sql", "model_tables.sql"):
        for stmt in sql_files.load(ML / f, **names):
            spark.sql(stmt)


def seed(spark, names: dict, force: bool) -> None:
    for table, rows in generate_dbxlab.generate().items():
        fqn = f"{names['sales']}.{table}"
        if force or _empty(spark, fqn):
            _df(spark, rows, fqn).write.mode("overwrite").insertInto(fqn)
            print(f"{fqn}: {len(rows)} rows (demo data)")
        else:
            print(f"{fqn}: not empty, kept (--force to rewrite)")


def source_rows(spark, names: dict) -> dict:
    """What the features are built from: the sales facts (AI-10), customer prices and inventory over time (AI-12, plus
    AI-02's ingested inventory for today), the SKU model and verified evidence (AI-03, AI-08, AI-09)."""
    s, p = names["sales"], names["product"]
    inventory = _rows(spark, f"SELECT sku_id, as_of, available, lead_time_days FROM {s}.inventory_history")
    inventory += _rows(spark, f"SELECT sku_id, CAST(_release_date AS TIMESTAMP) AS as_of, available, lead_time_days "
                              f"FROM {s}.inventory_snapshot")
    return {
        "facts": _rows(spark, f"SELECT quote_id, account_id, sku_id, quantity, CAST(unit_price AS DOUBLE) AS unit_price, "
                              f"CAST(list_price AS DOUBLE) AS list_price, outcome, issued_at, decided_at "
                              f"FROM {s}.quote_fact"),
        "orders": _rows(spark, f"SELECT account_id, order_date FROM {s}.order_line"),
        "prices": _rows(spark, f"SELECT account_id, observed_at, current_price FROM {s}.customer_price_history"),
        "inventory": inventory,
        "skus": _rows(spark, f"SELECT sku_id, product_id, material, intended_use FROM {p}.dbxlab_sku"),
        "evidence": _rows(spark, f"SELECT product_id, sku_id, attribute_name, attribute_value, verification_status, "
                                 f"verified_at FROM {p}.glove_evidence WHERE attribute_name = 'chemo_tested'"),
    }


def build(spark, names: dict) -> dict:
    src = source_rows(spark, names)
    end = datetime.now(timezone.utc).date()
    return F.build(src["facts"], src["orders"], src["prices"], src["inventory"], src["skus"], src["evidence"],
                   end=max(end, generate_dbxlab.TODAY.date()))


def features(spark, names: dict) -> None:
    from databricks.feature_engineering import FeatureEngineeringClient
    fe = FeatureEngineeringClient()
    built = build(spark, names)
    ml = names["ml"]
    _df(spark, built["quote_labels"], f"{ml}.quote_labels").write.mode("overwrite").insertInto(f"{ml}.quote_labels")
    for table in ("account_features", "sku_features", "quote_context_features"):
        F.write_feature_table(fe, f"{ml}.{table}", _df(spark, built[table], f"{ml}.{table}"))
        print(f"{ml}.{table}: {len(built[table])} rows merged")


def training_set(spark, names: dict) -> None:
    from databricks.feature_engineering import FeatureEngineeringClient
    from pyspark.sql import functions as fn
    fe = FeatureEngineeringClient()
    ml = names["ml"]
    labels = spark.table(f"{ml}.quote_labels").join(
        spark.table(f"{ml}.quote_context_features").drop("sent_at"), "quote_id")
    df = F.create_training_set(fe, labels, names, exclude=F.RAW_INPUTS).load_df()
    day = fn.to_date("sent_at")
    df = df.withColumn("split", fn.when(day <= fn.lit(F.TRAIN_END), "train").when(day <= fn.lit(F.VALID_END), "valid")
                       .when(day <= fn.lit(F.TEST_END), "test"))
    leaked = [c for c in F.EXCLUDED if c in df.columns]
    if leaked:
        raise F.LeakageError(f"excluded columns in the training set: {leaked}")
    rows = [r.asDict() for r in df.collect()]
    pure = build(spark, names)["training"]
    problems = F.compare(pure, rows, F.FEATURES) + F.check_training_set(pure, dict(zip(
        ("train", "valid", "test"), F.time_split(pure))))
    if problems:
        raise F.LeakageError(f"{len(problems)} problem(s), first: {problems[0]}")
    _df(spark, rows, f"{ml}.win_training_set").write.mode("overwrite").insertInto(f"{ml}.win_training_set")
    counts = {s: sum(1 for r in rows if r["split"] == s) for s in ("train", "valid", "test")}
    print(f"{ml}.win_training_set: {counts}; point in time, no excluded column, splits disjoint")


# ------------------------------------------------------------------ AI-13

def train_models(spark, names: dict, experiment: str, git_commit: str) -> None:
    from databricks.feature_engineering import FeatureEngineeringClient
    decision = train.train_all(spark, FeatureEngineeringClient(), names, experiment, git_commit)
    row = {"selected_at": datetime.now(timezone.utc), "training_set_version": decision["training_set_version"],
           "git_commit": git_commit, "status": decision["status"], "run_id": decision["run_id"],
           "run_name": decision["run_name"], "baseline_test_auc": decision["baseline_test_auc"],
           "reason": decision["reason"], "candidates": json.dumps(decision["candidates"])}
    fqn = f"{names['ml']}.model_selection"
    _df(spark, [row], fqn).write.mode("append").insertInto(fqn)
    print(f"{decision['status']}: {decision['reason']}")


# ------------------------------------------------------------------ AI-14

def _latest_auc(spark, fe, names: dict, uri: str, month: list[dict]) -> float:
    df = spark.createDataFrame(month).join(spark.table(f"{names['ml']}.quote_context_features").drop("sent_at"),
                                           "quote_id")
    scored = [r.asDict() for r in fe.score_batch(model_uri=uri, df=df).select("won", "prediction").collect()]
    return metrics.roc_auc([r["won"] for r in scored], [score.win_probability(r["prediction"]) for r in scored])


def register_model(spark, names: dict, endpoint: str | None, app_sp: str | None) -> None:
    from databricks.feature_engineering import FeatureEngineeringClient
    fe = FeatureEngineeringClient()
    ml = names["ml"]
    sel = spark.sql(f"SELECT * FROM {ml}.model_selection ORDER BY selected_at DESC LIMIT 1").collect()
    if not sel or sel[0]["status"] != "selected":
        print("the latest training run selected nothing: nothing to register, the champion stays")
        return
    if sel[0]["run_name"] == "automl":
        print("AutoML won the comparison: it is a benchmark, logged without the feature lookups. Retrain its "
              "configuration as a candidate in quote_ai.ml.train, then run quote_ai_train again; the champion stays")
        return
    name = register.model_name(names)
    champion = register.alias_version(name, register.CHAMPION)
    mv = register.register(sel[0]["run_id"], name)
    month = register.latest_month(r.asDict() for r in spark.table(f"{ml}.quote_labels").collect())
    challenger_auc = _latest_auc(spark, fe, names, register.alias_uri(name, register.CHALLENGER), month)
    champion_auc = (_latest_auc(spark, fe, names, register.alias_uri(name, register.CHAMPION), month)
                    if champion else None)
    promoted, reason = register.should_promote(challenger_auc, champion_auc)
    if promoted:
        register.set_champion(name, str(mv.version))
        if endpoint:
            register.point_endpoint(endpoint, name, str(mv.version))
    for stmt in register.grant_statements(name, [app_sp]):
        spark.sql(stmt)
    row = register.promotion_row(str(mv.version), challenger_auc, champion, champion_auc, promoted, reason,
                                 sel[0]["run_id"], datetime.now(timezone.utc))
    _df(spark, [row], f"{ml}.model_promotion").write.mode("append").insertInto(f"{ml}.model_promotion")
    print(f"version {mv.version} @challenger; {reason}")


def score_open_quotes(spark, names: dict) -> None:
    from databricks.feature_engineering import FeatureEngineeringClient
    rows = score.open_quotes(spark, names)
    version = register.alias_version(register.model_name(names), register.CHAMPION)
    if version is None:
        raise score.ScoringError("no @champion yet: run quote_ai_ml_register first")
    scored = score.score_batch(spark, FeatureEngineeringClient(), names, rows, version)
    problems = score.check_scores([r["quote_id"] for r in rows], scored)
    if problems:
        raise score.ScoringError(f"{len(problems)} problem(s), first: {problems[0]}")
    now = datetime.now(timezone.utc)
    fqn = f"{names['ml']}.open_quote_scores"
    _df(spark, [r | {"scored_at": now, "won": None} for r in scored], fqn).write.mode("append").insertInto(fqn)
    print(f"{fqn}: {len(scored)} open quotes scored by @champion (version {version}); {score.LABEL}")


def main(argv=None) -> None:
    a = parse(argv if argv is not None else sys.argv[1:])
    from pyspark.sql import SparkSession
    spark = SparkSession.builder.getOrCreate()
    names = sql_files.names_for(a.catalog, dict(p.split("=", 1) for p in a.schemas.split(",") if p))
    if a.command == "setup":
        setup(spark, names)
    elif a.command == "seed":
        seed(spark, names, a.force)
    elif a.command == "features":
        features(spark, names)
    elif a.command == "training-set":
        training_set(spark, names)
    elif a.command == "train":
        train_models(spark, names, a.experiment, a.git_commit)
    elif a.command == "register":
        register_model(spark, names, a.endpoint, a.app_sp)
    elif a.command == "score":
        score_open_quotes(spark, names)
    elif a.command == "monitor":
        table = f"{names['ml']}.open_quote_scores"
        monitor.create_or_update_monitor(table, names["monitoring"],
                                         f"/Workspace/Shared/quote_ai/monitoring/{a.catalog}")
        monitor.refresh(table)
    elif a.command == "drift":
        fqn = f"{names['sales']}.customer_price_history"
        rows = generate_dbxlab.drift_month(end=datetime.now(timezone.utc))
        _df(spark, rows, fqn).write.mode("append").insertInto(fqn)
        print(f"{fqn}: {len(rows)} drift-demo rows appended (source 'drift demo'); now run features, then score")


if __name__ == "__main__":
    main()
