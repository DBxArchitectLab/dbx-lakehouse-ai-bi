def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)").encode("ascii", "replace").decode()


def pdf_bytes(lines: list[str]) -> bytes:
    """A valid one-page PDF (Helvetica, uncompressed), with no dependency. Up to about 55 lines."""
    text = "BT /F1 10 Tf 50 760 Td 13 TL " + " ".join(f"({_esc(l)}) Tj T*" for l in lines) + " ET"
    objs = ["<< /Type /Catalog /Pages 2 0 R >>", "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
            "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> "
            "/Contents 5 0 R >>",
            "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
            f"<< /Length {len(text)} >>\nstream\n{text}\nendstream"]
    out, offsets = b"%PDF-1.4\n", []
    for i, o in enumerate(objs, start=1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n{o}\nendobj\n".encode()
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    out += "".join(f"{o:010d} 00000 n \n" for o in offsets).encode()
    out += f"trailer\n<< /Size {len(objs) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    return out


def pdf_text(data: bytes) -> str:
    """The text of a PDF written by pdf_bytes, one line per Tj (the generator self-test; not a general parser)."""
    s = data.decode("latin-1")
    lines = re.findall(r"\(((?:\\.|[^\\)])*)\) Tj", s)
    return "\n".join(re.sub(r"\\(.)", r"\1", l) for l in lines)


def checksum(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def registry_row(doc: Doc, volume_root: str, data: bytes) -> dict:
    """The quote_ai_product.document_registry row of a received document (is_current is set by the registration)."""
    return {"document_id": doc.document_id, "document_type": doc.document_type, "supplier": doc.supplier,
            "catalog_no": ",".join(c for _, _, c in doc.products) or None, "product_id": doc.product_id,
            "sku_id": None, "version": doc.version, "effective_date": doc.effective_date,
            "path": f"{volume_root.rstrip('/')}/{doc.path}", "checksum": checksum(data), "is_current": True,
            "received_via": doc.received_via}


def truth(docs: Iterable[Doc]) -> list[dict]:
    """One line per document for evaluation/quote_ai/v1/product_facts/documents.jsonl."""
    return [{"id": f"doc-{d.document_id}-v{d.version}", "document_id": d.document_id, "version": d.version,
             "document_type": d.document_type, "path": d.path, "expected": d.truth}
            for d in docs if d.truth]


def truth_jsonl(docs: Iterable[Doc]) -> str:
    return "".join(json.dumps(t, sort_keys=True) + "\n" for t in truth(docs))


def read_fields(text: str) -> dict:
    """A stand-in for ai_extract over these generated PDFs, for tests and the app's local demo only: the same labels
    the pipeline asks for, as strings. On Databricks the pipeline's AI Function does this."""
    def one(label):
        m = re.search(rf"^{label}:\s*(.+)$", text, re.M)
        return m.group(1).strip() if m else None
    out = {"document_id": one("Document ID"), "version": one("Version"), "supplier": one("Supplier"),
           "catalog_numbers": ", ".join(re.findall(r"Catalog (\S+)", text)) or None,
           "aql": one("AQL"), "thickness": one("Thickness"), "tensile_strength": one("Tensile strength"),
           "material": one("Material"), "powder_free": one("Powder-free")}
    m = re.search(r"Standard:\s*(.+)$", text, re.M)
    out["standard"] = m.group(1).strip() if m else None
    results = re.findall(r"^\s+([A-Z][a-z]+): (.+ min)$", text, re.M)
    if results:
        out["drugs"] = ", ".join(d for d, _ in results)
        out["results"] = "; ".join(f"{d}: {r}" for d, r in results)
    if re.search(r"chemo", text, re.I) and not results:
        out["chemo_claim"] = "true"
    return {k: v for k, v in out.items() if v}


def demo_registry(docs: Iterable[Doc], root: str = "/Volumes/demo/quote_ai_ai/quote_ai_documents") -> list[dict]:
    """Registry rows for a set of documents, with is_current set (the job does this with a MERGE)."""
    from quote_ai.product.evidence import current_versions
    return current_versions(registry_row(d, root, pdf_bytes(d.lines())) for d in docs if d.document_type != "request")


def sku_refs(skus: Iterable[Mapping] | None = None, unverified: Iterable[str] = ()):
    """The this-product side for the demo: every SKU with its (stand-in) catalog number, mapping verified unless
    listed in `unverified`."""
    from quote_ai.product.evidence import SkuRef
    out = []
    for s in (skus if skus is not None else catalog.skus()):
        cat = s.get("supplier_catalog_number") or f"{STAND_IN[s['product_id']]}-{s['size']}"
        out.append(SkuRef(sku_id=s["sku_id"], product_id=s["product_id"], supplier=None, catalog_no=cat,
                          mapping_verified=s["sku_id"] not in set(unverified)))
    return out


def demo_evidence(scenarios: Iterable[str] = (), signoffs: Mapping | None = None, at=None,
                  registry_edit=None) -> tuple[list, list[Doc], list[dict]]:
    """The whole AI-09 flow without a workspace: documents -> PDFs -> read_fields -> registry -> the five checks.
    signoffs: {(document_id, version): reviewer} on top of demo:qa for every spec sheet. registry_edit: a function
    that may change the registry rows (tests). Returns (supplier_quality_evidence rows, documents, registry)."""
    from datetime import datetime, timezone

    from quote_ai.product import evidence
    at = at or datetime(2026, 11, 20, tzinfo=timezone.utc)
    docs = documents(None, scenarios)
    reg = demo_registry(docs)
    if registry_edit:
        reg = evidence.current_versions(registry_edit(reg))
    text = {f"/Volumes/demo/quote_ai_ai/quote_ai_documents/{d.path}": read_fields(pdf_text(pdf_bytes(d.lines())))
            for d in docs}
    qa = {(d.document_id, d.version): ("demo:qa", at) for d in docs if demo_signed(d)}
    qa |= {k: (who, at) for k, who in (signoffs or {}).items()}
    parsed = [evidence.to_document(r, text.get(r["path"]), reg) for r in reg
              if r["document_type"] in ("spec_sheet", "test_report", "marketing")]
    return evidence.document_evidence(parsed, sku_refs(), qa, at), docs, reg


def demo_signed(doc: Doc) -> bool:
    return doc.document_type == "spec_sheet" or doc.document_id in PRE_SIGNED
