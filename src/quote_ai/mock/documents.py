"""Synthetic supplier documents for DBxLab (AI-09): spec sheets, test reports, a marketing sheet, price lists and the
Lakeside request, as small PDFs, with the true value of every field. Demo data, made for DBxLab Medical Supply: no
real supplier's document and no standards text (DBxLab writes its own short notes). Sales quoting only, not clinical.

  documents(skus, scenarios)   what is in the volume; scenarios add the demo's drops, cumulatively:
      glove_a_report         RPT-CHEMO-A, Glove A's chemo test report (its QA sign-off is a separate, manual step)
      other_catalog_report   RPT-CHEMO-N310: a valid report for another catalog number, filed against Glove A
      spec_v4                SPEC-A version 4, with a new thickness (supersedes version 3)
      glove_b_report         RPT-CHEMO-B, Glove B's report (AI-26)
  pdf_bytes / pdf_text       a minimal one-page PDF writer, and the reader the generator self-test uses
  registry_row               the document_registry row a document gets when it is received
  truth                      the true values, one per document (evaluation/quote_ai/v1/product_facts/documents.jsonl)

Catalog numbers come from the SKUs (dbxlab_sku.supplier_catalog_number, bound to real GUDID devices by AI-03); a
SKU with none gets a stand-in (N-300-M for Glove A size M), so the generator also runs without a workspace.
"""
from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Iterable, Mapping
from datetime import date

from pydantic import BaseModel

from quote_ai.mock import catalog

DEMO = "Synthetic demo data for DBxLab Medical Supply. Sales quoting only, not for clinical use."
SUPPLIER = "Synthetic Glove Supply Co."
STANDARD = "ASTM D6978"
DRUGS = ["Carmustine", "Cisplatin", "Cyclophosphamide", "Doxorubicin", "Etoposide", "Fluorouracil", "Paclitaxel"]
STAND_IN = {"GLOVE-A": "N-300", "GLOVE-B": "N-301", "GLOVE-C": "N-302", "GLOVE-D": "N-303", "GLOVE-E": "N-304",
            "GLOVE-F": "N-310"}
SCENARIOS = ("glove_a_report", "other_catalog_report", "spec_v4", "glove_b_report")
# Signed off by demo:qa when generated (demo data only): every spec sheet, and the reports already on file before
# AI-09 (Gloves C and D). Glove A's report is signed off by a person, on camera; the misfiled report never is.
PRE_SIGNED = {"RPT-CHEMO-C", "RPT-CHEMO-D"}
FOLDERS = {"spec_sheet": "specs", "test_report": "test_reports", "marketing": "marketing",
           "price_list": "price_lists", "request": "requests"}
README = f"""# QuoteAI supplier documents (demo data)

Every file in this volume is synthetic, generated by src/quote_ai/mock/documents.py for DBxLab Medical Supply, a
fictional distributor. No real supplier, product claim or test result. {DEMO}

specs/          spec sheets: AQL, thickness, tensile strength
test_reports/   chemotherapy drug test reports: drug list, standard, a result per drug
marketing/      a marketing sheet (never evidence)
price_lists/    supplier price lists
requests/       quote requests uploaded in the QuoteAI app
"""

# spec values per product: (aql, thickness as written, thickness in mm, tensile)
SPECS = {"GLOVE-A": (1.5, "0.08 mm", 0.08, "14 MPa"), "GLOVE-B": (1.5, "0.07 mm", 0.07, "14 MPa"),
         "GLOVE-C": (2.5, "0.10 mm", 0.10, "15 MPa"), "GLOVE-D": (1.5, "3.1 mil", 0.0787, "16 MPa"),
         "GLOVE-E": (2.5, "0.12 mm", 0.12, "18 MPa"), "GLOVE-F": (1.5, "0.08 mm", 0.08, "14 MPa")}


class Doc(BaseModel):
    document_id: str
    version: int
    document_type: str
    product_id: str | None
    effective_date: date
    received_via: str = "supplier_portal"
    supplier: str = SUPPLIER
    products: list[tuple[str, str, str]] = []     # (size, supplier, catalog number)
    truth: dict = {}
    body: list[str] = []

    @property
    def path(self) -> str:
        return f"{FOLDERS[self.document_type]}/{self.document_id}_v{self.version}.pdf"

    def lines(self) -> list[str]:
        head = [f"DBxLab Medical Supply - {self.document_type.replace('_', ' ')}", DEMO, "",
                f"Document ID: {self.document_id}", f"Version: {self.version}",
                f"Effective date: {self.effective_date.isoformat()}", f"Supplier: {self.supplier}"]
        if self.products:
            head += ["", "Products covered:"] + [f"  Size {s}  Supplier {sup}  Catalog {c}"
                                                 for s, sup, c in self.products]
        return head + [""] + self.body


def _sku_refs(skus: Iterable[Mapping]) -> dict[str, list[tuple[str, str, str]]]:
    out: dict[str, list[tuple[str, str, str]]] = {}
    for s in skus:
        cat = s.get("supplier_catalog_number") or f"{STAND_IN[s['product_id']]}-{s['size']}"
        out.setdefault(s["product_id"], []).append((s["size"], s.get("supplier") or SUPPLIER, cat))
    return out


def _spec(pid: str, products, version: int, thickness: tuple[str, float] | None = None) -> Doc:
    aql, t_text, t_mm, tensile = SPECS[pid]
    if thickness:
        t_text, t_mm = thickness
    letter = pid[-1]
    return Doc(document_id=f"SPEC-{letter}", version=version, document_type="spec_sheet", product_id=pid,
               effective_date=date(2026, version, 1), products=products,
               truth={"material": "nitrile", "powder_free": True, "aql": aql, "thickness_mm": t_mm,
                      "tensile_mpa": float(tensile.split()[0])},
               body=["Specification", "Material: nitrile", "Powder-free: yes", f"AQL: {aql:g}",
                     f"Thickness: {t_text}", f"Tensile strength: {tensile}",
                     "", "DBxLab note: values as supplied; checked by DBxLab QA before use in a quote."])


def _report(doc_id: str, pid: str, products, filed_against: str | None = None) -> Doc:
    results = {d: ("45 min" if d == "Carmustine" else ">240 min") for d in DRUGS}
    return Doc(document_id=doc_id, version=1, document_type="test_report", product_id=filed_against or pid,
               effective_date=date(2026, 9, 15), products=products,
               truth={"standard": STANDARD, "drugs": DRUGS, "results": results,
                      "catalog_numbers": [c for _, _, c in products]},
               body=[f"Chemotherapy drug permeation test report. Standard: {STANDARD}",
                     "Drugs tested and breakthrough time:"] + [f"  {d}: {r}" for d, r in results.items()]
               + ["", "DBxLab note: synthetic results for the demo; not a real test."])


def documents(skus: Iterable[Mapping] | None = None, scenarios: Iterable[str] = ()) -> list[Doc]:
    """Every document in the volume for these scenarios (cumulative). skus: dbxlab_sku rows (+ optional supplier)."""
    scenarios = set(scenarios)
    unknown = scenarios - set(SCENARIOS)
    if unknown:
        raise ValueError(f"unknown scenarios: {sorted(unknown)}")
    refs = _sku_refs(skus if skus is not None else catalog.skus())
    docs = [_spec("GLOVE-A", refs["GLOVE-A"], 2, ("0.07 mm", 0.07))]
    docs += [_spec(pid, refs[pid], 3) for pid in sorted(refs)]
    if "spec_v4" in scenarios:
        docs.append(_spec("GLOVE-A", refs["GLOVE-A"], 4, ("0.09 mm", 0.09)))
    docs += [_report("RPT-CHEMO-C", "GLOVE-C", refs["GLOVE-C"]), _report("RPT-CHEMO-D", "GLOVE-D", refs["GLOVE-D"])]
    if "glove_a_report" in scenarios:
        docs.append(_report("RPT-CHEMO-A", "GLOVE-A", refs["GLOVE-A"]))
    if "other_catalog_report" in scenarios:      # a valid report, for Glove F's catalog numbers, filed against A
        docs.append(_report("RPT-CHEMO-N310", "GLOVE-F", refs["GLOVE-F"], filed_against="GLOVE-A"))
    if "glove_b_report" in scenarios:
        docs.append(_report("RPT-CHEMO-B", "GLOVE-B", refs["GLOVE-B"]))
    docs.append(Doc(document_id="MKT-B", version=1, document_type="marketing", product_id="GLOVE-B",
                    effective_date=date(2026, 6, 1), received_via="sales_email", products=refs["GLOVE-B"],
                    truth={"chemo_claim": True},
                    body=["Glove B: chemo-rated comfort for every shift!", "Ask your rep about volume pricing."]))
    for i, pids in enumerate((["GLOVE-A", "GLOVE-B"], ["GLOVE-C", "GLOVE-D"], ["GLOVE-E", "GLOVE-F"]), start=1):
        rows = [(c, round(5.80 + 0.1 * j, 2)) for j, pid in enumerate(pids) for _, _, c in refs[pid]]
        docs.append(Doc(document_id=f"PL-{i}", version=1, document_type="price_list", product_id=None,
                        effective_date=date(2026, 10, 1),
                        truth={"prices": {c: p for c, p in rows}},
                        body=["Supplier price list, USD per box"] + [f"  {c}  {p:.2f}" for c, p in rows]))
    docs.append(Doc(document_id="REQ-LAKESIDE", version=1, document_type="request", product_id=None,
                    effective_date=date(2026, 11, 14), received_via="app_upload", supplier="Lakeside Regional Clinic",
                    body=_wrap(LAKESIDE_REQUEST)))
    return docs


LAKESIDE_REQUEST = ("Lakeside Regional Clinic needs 400 boxes of powder-free nitrile exam gloves, chemo-tested, "
                    "latex-free, sizes S to XL, non-sterile is fine. They pay about $8 a box today for Brand X and "
                    "need delivery in 10 days.")


def _wrap(text: str, width: int = 90) -> list[str]:
    out, line = [], ""
    for word in text.split():
        if len(line) + len(word) + 1 > width:
            out.append(line)
            line = word
        else:
            line = f"{line} {word}".strip()
    return out + ([line] if line else [])


